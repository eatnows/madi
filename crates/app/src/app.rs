impl View for Madi {
    fn view(&self, cx: &mut Cx) -> El {
        let p = Palette::new(self.resolve_dark(cx));
        let mut middle = div().row().grow();
        if !self.focus_mode {
            middle = middle.child(self.rail(&p)).child(div().w(1.).bg(p.border)).child(self.sidebar(cx, &p));
        }
        let body = div().col().grow().child(middle.child(self.main_area(cx, &p))).child(if self.git_graph_open { self.graph_view(cx, &p) } else { div() });
        let mut root = div().bg(p.bg).text_color(p.text).text_size(13.).child(self.topbar(&p)).child(body);
        if !self.focus_mode {
            root = root.child(self.status_bar(&p));
        }
        if let Some(settings) = self.settings_modal(&p) {
            root = root.child(settings);
        }
        if let Some(confirm) = self.close_confirm_modal(&p) {
            root = root.child(confirm);
        }
        if let Some(confirm) = self.project_close_modal(&p) {
            root = root.child(confirm);
        }
        if let Some(confirm) = self.worktree_remove_modal(&p) {
            root = root.child(confirm);
        }
        if let Some(picker) = self.branch_picker_view(&p) {
            root = root.child(picker);
        }
        if let Some(menu) = self.context_menu_view(&p) {
            root = root.child(menu);
        }
        if let Some(quick_open) = self.quick_open_view(&p) {
            root = root.child(quick_open);
        }
        if let Some(search) = self.project_search_view(&p) { root = root.child(search); }
        root
    }

    fn event(&mut self, event: &Event, cx: &mut Cx) {
        match event {
            Event::FocusChanged(focused) => self.window_focused = *focused,
            Event::Scroll { .. } if self.git_graph_open => self.load_graph_if_near_end(cx),
            Event::KeyDown { key, text, .. } => {
                if self.quick_open_key(key, text.as_deref(), cx) {
                    return;
                }
                if self.project_search_key(key, text.as_deref(), cx) { return; }
                if self.picker_key(key, text.as_deref(), cx) {
                    return;
                }
                if self.git_graph_open {
                    match key {
                        gyeol::Key::Named(NamedKey::ArrowUp) => { self.move_graph_commit(-1); return; }
                        gyeol::Key::Named(NamedKey::ArrowDown) => { self.move_graph_commit(1); return; }
                        _ => {}
                    }
                }
                if self.close_confirm.is_some() {
                    if matches!(key, gyeol::Key::Named(NamedKey::Escape)) { self.close_confirm = None; }
                    return;
                }
                if self.settings_key(key, cx) {
                    return;
                }
                if matches!(key, gyeol::Key::Char(c) if c == ",") && cx.modifiers.command() {
                    self.open_settings();
                    return;
                }
                if matches!(key, gyeol::Key::Char(c) if c.eq_ignore_ascii_case("p")) && cx.modifiers.command() {
                    self.open_quick_open();
                    return;
                }
                if matches!(key, gyeol::Key::Char(c) if c.eq_ignore_ascii_case("f")) && cx.modifiers.command() && cx.modifiers.shift {
                    self.open_project_search();
                    return;
                }
                self.editor_event(event, cx);
            }
            Event::Ime(ime) if self.quick_open_ime(ime) => {}
            Event::Ime(ime) if self.picker_ime(ime) => {}
            _ if !self.settings_open && self.close_confirm.is_none() => self.editor_event(event, cx),
            _ => {}
        }
    }
}

