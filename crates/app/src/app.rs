    fn tab_bar(&self, p: &Palette) -> El {
        let ws = self.workspace();
        let active = ws.and_then(|w| w.active);
        let mut tabs: Vec<El> = ws.into_iter().flat_map(|w| w.tabs.iter().enumerate()).map(|(i, tab)| {
            let dirty = tab.editor.doc.is_dirty();
            let is_active = active == Some(i);
            let title = text(tab.title.clone()).text_size(12.).text_color(if is_active { p.text_strong } else { p.text_dim });
            let close = div()
                .w(14.)
                .items_center()
                .rounded(4.)
                .hover_bg(p.border)
                .on_click(move |s: &mut Madi, _| s.close_tab(i))
                .child(text(if dirty { "●" } else { "×" }).text_size(12.).text_color(if dirty { p.amber } else { p.text_dim }));
            div()
                .row()
                .items_center()
                .h(34.)
                .px(12.)
                .gap(8.)
                .bg(if is_active { p.bg } else { Color::TRANSPARENT })
                .hover_bg(if is_active { p.bg } else { p.selected })
                .on_mouse_down(move |s: &mut Madi, _, event| {
                    if event.button == gyeol::MouseButton::Left {
                        s.begin_tab_drag(i, event.pos.0);
                    }
                })
                .on_drag(|s: &mut Madi, _, event| s.drag_tab(event.pos.0))
                .on_mouse_up(|s: &mut Madi, _, _| s.end_tab_drag())
                .on_click(move |s: &mut Madi, _| s.activate_tab(i))
                .child(if tab.preview { title.text_italic() } else { title })
                .child(close)
                .child(div().w(1.).bg(p.border))
        }).collect();
        if let Some(diff) = ws.and_then(|w| w.diff.as_ref()) {
            let is_active = ws.is_some_and(|w| w.showing_diff);
            let title = diff.title.clone();
            tabs.push(
                div().row().items_center().h(34.).px(12.).gap(8.)
                    .bg(if is_active { p.bg } else { Color::TRANSPARENT }).hover_bg(p.selected)
                    .on_click(|s: &mut Madi, _| { s.workspace_mut().showing_diff = true; s.focus = Focus::Editor; })
                    .child(text(title).text_size(12.).text_color(if is_active { p.text_strong } else { p.text_dim }))
                    .child(div().w(14.).items_center().rounded(4.).hover_bg(p.border).on_click(|s: &mut Madi, _| s.close_diff()).child(text("×").text_size(12.).text_color(p.text_dim)))
                    .child(div().w(1.).bg(p.border)),
            );
        }
        div().col().child(div().row().h(34.).bg(p.chrome).children(tabs)).child(div().h(1.).bg(p.border))
    }

    fn diff_view(&self, cx: &Cx, p: &Palette) -> El {
        let Some(diff) = self.workspace().and_then(|ws| ws.diff.as_ref()) else { return div().grow() };
        self.split_diff_view(cx, p, &diff.file, "worktree-diff")
    }

    fn graph_diff_cell(cell: Option<&madi_git::diff_layout::Cell>, p: &Palette, width: f32) -> El {
        let (bg, fg) = match cell.map(|cell| cell.tag) {
            Some("insert") => (p.add_bg, p.add_fg),
            Some("delete") => (p.del_bg, p.del_fg),
            _ => (Color::TRANSPARENT, p.text),
        };
        let line = cell.and_then(|cell| cell.lineno).map(|line| line.to_string()).unwrap_or_default();
        let content = cell.map(|cell| cell.text.to_string()).unwrap_or_default();
        div().row().items_center().w(width).h(20.).bg(bg)
            .child(div().w(42.).px(6.).justify_end().child(text(line).text_size(10.).text_color(p.text_dim)))
            .child(text(content).text_size(11.).text_family(editor::MONO).text_color(fg))
    }

    /// The original app's side-by-side diff layout, used both for worktree tabs and commit detail.
    fn split_diff_view(&self, cx: &Cx, p: &Palette, file: &FileDiff, id: &'static str) -> El {
        if file.binary {
            return div().grow().items_center().justify_center().child(text("Binary file — diff is unavailable").text_size(12.).text_color(p.text_dim));
        }
        let layout = madi_git::diff_layout::DiffLayout::new(&file.lines);
        let half_width = (62. + layout.widest_line(false) as f32 * self.config.font_size() * 0.62).max(300.);
        let full_width = half_width * 2.;
        let path = file.path.clone();
        let rows = uniform_list(cx, (id, &self.repo, &path), layout.split.len(), 20., |ix| {
            match &layout.split[ix] {
                madi_git::diff_layout::Row::Gap => div().w(full_width).h(20.).items_center().justify_center().bg(p.panel).child(text("⋯ unchanged ⋯").text_size(10.).text_color(p.text_dim)),
                madi_git::diff_layout::Row::Pair(old, new) => div().row().w(full_width).h(20.)
                    .child(Self::graph_diff_cell(old.as_ref(), p, half_width))
                    .child(div().w(1.).h_full().bg(p.border))
                    .child(Self::graph_diff_cell(new.as_ref(), p, half_width)),
            }
        }).grow().scrollbar(p.text_dim.with_alpha(0.4));
        div().id((id, "x", &self.repo, &path)).grow().overflow_x_scroll().child(div().w(full_width).h_full().child(rows.w(full_width)))
    }

    fn graph_view(&self, cx: &Cx, p: &Palette) -> El {
        let handle = |kind: GraphHandle| {
            div().w(4.).h_full().hover_bg(p.border).on_mouse_down(move |s: &mut Madi, _, event| {
                if event.button == gyeol::MouseButton::Left {
                    s.begin_graph_drag(kind, event.pos);
                }
            }).on_drag(|s: &mut Madi, _, event| s.drag_graph(event.pos)).on_mouse_up(|s: &mut Madi, _, _| s.end_graph_drag())
        };
        let rows = uniform_list(cx, ("git-graph", &self.repo), self.graph_commits.len(), 32., |i| {
            let commit = &self.graph_commits[i];
            let row = &self.graph_rows[i];
            let lane_x = 10. + row.lane as f32 * 16.;
            let colors = [p.amber, p.green, p.red, p.text_dim];
            let lane = |lane: usize| 10. + lane as f32 * 16.;
            let stroke = |lane: usize| DrawPath::stroke(colors[lane % colors.len()], 2.);
            let mut graph_paths = Vec::new();
            for other in &row.pass_through {
                let x = lane(*other);
                graph_paths.push(stroke(*other).move_to(x, 0.).line_to(x, 32.));
            }
            graph_paths.push(stroke(row.lane).move_to(lane_x, 0.).line_to(lane_x, 16.));
            if row.continues {
                graph_paths.push(stroke(row.lane).move_to(lane_x, 16.).line_to(lane_x, 32.));
            }
            for other in &row.converge_from {
                let from = lane(*other);
                graph_paths.push(stroke(*other).move_to(from, 0.).cubic_to(from, 9., lane_x, 7., lane_x, 16.));
            }
            for other in &row.diverge_to {
                let to = lane(*other);
                graph_paths.push(stroke(*other).move_to(lane_x, 16.).cubic_to(lane_x, 25., to, 23., to, 32.));
            }
            let lanes = div().w((row.max_lane + 1) as f32 * 16. + 12.).h(32.)
                .child(paths(graph_paths).inset(0.))
                .child(div().absolute().left(lane_x - 4.).top(12.).size(10.).rounded(5.).bg(colors[row.lane % 4]));
            div().row().items_center().h(32.).px(12.).gap(10.).min_w(760.).bg(if self.graph_selected == Some(i) { p.selected } else { Color::TRANSPARENT }).hover_bg(p.selected).on_click(move |s: &mut Madi, _| s.select_graph_commit(i))
                .child(lanes)
                .child(text(commit.summary.clone()).text_size(12.).text_color(p.text_strong).grow())
                .child(text(commit.author_name.clone()).text_size(11.).text_color(p.text_dim).w(120.))
                .child(text(time::relative(std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map_or(0, |d| d.as_secs() as i64), commit.timestamp)).text_size(11.).text_color(p.text_dim).w(70.))
                .child(text(commit.short_oid.clone()).text_size(11.).text_family(editor::MONO).text_color(p.text_dim).w(64.))
        }).grow().scrollbar(p.text_dim.with_alpha(0.4));
        let changes = if self.graph_selected.is_none() {
            div().grow().items_center().justify_center().child(text("Select a commit to see its changed files").text_size(12.).text_color(p.text_dim))
        } else {
            let files = uniform_list(cx, ("graph-files", &self.repo), self.graph_files.len(), 24., |ix| {
                let file = &self.graph_files[ix];
                let selected = self.graph_file_selected == Some(ix);
                div().row().items_center().px(8.).rounded(4.).bg(if selected { p.selected } else { Color::TRANSPARENT }).hover_bg(p.selected)
                    .on_click(move |s: &mut Madi, _| s.select_graph_file(ix))
                    .child(text(file.path.clone()).text_size(11.).text_color(p.text).grow())
                    .child(text(format!("+{} −{}", file.additions, file.deletions)).text_size(10.).text_color(p.text_dim))
            }).grow().p(6.).scrollbar(p.text_dim.with_alpha(0.4));
            let diff = self.graph_file_selected.and_then(|ix| self.graph_files.get(ix)).map_or_else(
                || div().grow().items_center().justify_center().child(text("Select a changed file").text_size(12.).text_color(p.text_dim)),
                |file| self.split_diff_view(cx, p, file, "graph-diff"),
            );
            div().row().grow().child(div().w(self.graph_files_width).h_full().border(1., p.border_soft).child(files)).child(handle(GraphHandle::FilesWidth)).child(diff)
        };
        div().h(self.graph_height).border(1., p.border).bg(p.panel)
            .child(div().row().items_center().h(34.).px(12.).child(div().px(6.).rounded(5.).hover_bg(p.selected).on_mouse_down(|s: &mut Madi, _, event| {
                if event.button == gyeol::MouseButton::Left {
                    s.open_branch_picker(BranchPickerTarget::Graph, event.pos);
                }
            }).child(text(format!("Graph · {} ⌄", self.graph_branch)).text_size(12.).text_color(p.text_strong))).child(text(if self.graph_follow { "following worktree" } else { "pinned" }).text_size(10.).text_color(if self.graph_follow { p.green } else { p.amber })).child(div().grow()).child(div().px(6.).hover_bg(p.selected).on_click(|s: &mut Madi, _| s.git_graph_open = false).child(text("×").text_color(p.text_dim))))
            .child(div().h(1.).bg(p.border)).child(div().row().grow()
                .child(div().w(self.graph_width).h_full().border(1., p.border_soft).child(div().grow().overflow_x_scroll().child(rows.w(760.))))
                .child(handle(GraphHandle::GraphWidth))
                .child(changes))
            .child(div().absolute().top(0.).left(0.).right(0.).h(5.).hover_bg(p.border).on_mouse_down(|s: &mut Madi, _, event| {
                if event.button == gyeol::MouseButton::Left {
                    s.begin_graph_drag(GraphHandle::Height, event.pos);
                }
            }).on_drag(|s: &mut Madi, _, event| s.drag_graph(event.pos)).on_mouse_up(|s: &mut Madi, _, _| s.end_graph_drag()))
    }

    /// The shared branch picker from the GPUI app: typed filtering, slash-grouped folders and
    /// arrow/enter keyboard navigation. The state stays at the root so it can float above either
    /// the sidebar base button or the graph's branch selector.
    fn branch_picker_view(&self, p: &Palette) -> Option<El> {
        let picker = self.branch_picker.as_ref()?;
        let current = match picker.target {
            BranchPickerTarget::WorktreeBase(ix) => self.worktrees.get(ix).and_then(|worktree| self.pins.get(&worktree.path)).cloned().unwrap_or_default(),
            BranchPickerTarget::Graph => self.graph_branch.clone(),
        };
        let query = picker.query.clone();
        let rows = self.picker_rows().into_iter().enumerate().map(|(ix, row)| {
            let highlighted = picker.highlighted == ix;
            let base = div().row().items_center().h(26.).px(6.).rounded(4.)
                .bg(if highlighted { p.selected } else { Color::TRANSPARENT }).hover_bg(p.selected)
                .on_click(move |s: &mut Madi, _| s.activate_picker(ix));
            match row {
                BranchRow::Folder { full_path, segment, depth } => {
                    let open = !picker.collapsed.contains(&full_path) || !query.is_empty();
                    base.child(div().w(8. + depth as f32 * 14.)).child(text(if open { "▾" } else { "▸" }).text_size(10.).text_color(p.text_dim)).child(text(segment).text_size(11.).text_family(editor::MONO).text_color(p.text_dim))
                }
                BranchRow::Branch { full_path, depth } => {
                    let label = full_path.rsplit('/').next().unwrap_or(&full_path).to_string();
                    let chosen = full_path == current;
                    base.child(div().w(22. + depth as f32 * 14.)).child(text(label).text_size(11.).text_family(editor::MONO).text_color(p.text_strong)).child(div().grow()).child(if chosen { text("✓").text_size(11.).text_color(p.green) } else { text("") })
                }
            }
        });
        let search = if query.is_empty() { text("Search branches").text_size(11.).text_color(p.text_dim) } else { text(format!("{query}│")).text_size(11.).text_family(editor::MONO).text_color(p.text_strong) };
        Some(
            div().inset(0.).on_click(|s: &mut Madi, _| s.branch_picker = None).child(
                div().absolute().left(picker.anchor.0).top(picker.anchor.1 + 8.).w(260.).max_h(340.).rounded(6.).border(1., p.border).bg(p.chrome).on_click(|_: &mut Madi, _| {})
                    .child(div().h(31.).px(9.).items_center().border(1., p.border_soft).child(search))
                    .child(div().max_h(300.).overflow_y_scroll().p(4.).gap(1.).children(rows)),
            ),
        )
    }

    fn main_area(&self, cx: &mut Cx, p: &Palette) -> El {
        let content = if self.workspace().is_some_and(|ws| ws.showing_diff) {
            self.diff_view(cx, p)
        } else { match self.active_editor() {
            Some(ed) => {
                let focused = self.focus == Focus::Editor && self.window_focused;
                let blink_on = (self.blink_epoch.elapsed().as_millis() / BLINK.as_millis()) % 2 == 0;
                if focused {
                    cx.request_redraw_after(Duration::from_millis((BLINK.as_millis() - self.blink_epoch.elapsed().as_millis() % BLINK.as_millis()) as u64));
                }
                editor::view(ed, cx, p, self.config.font_size(), focused && blink_on)
            }
            None => div()
                .grow()
                .items_center()
                .justify_center()
                .gap(8.)
                .child(text("Nothing open").text_size(15.).text_color(p.text))
                .child(text("Pick a file in Files to edit it").text_size(12.).text_color(p.text_dim)),
        }};
        div().grow().child(self.tab_bar(p)).child(content)
    }

    fn status_bar(&self, p: &Palette) -> El {
        let details = self.active_editor().map(|e| {
            let (line, col) = e.doc.cursor_display();
            format!("Ln {line}, Col {col}   {}   UTF-8", e.doc.line_ending())
        });
        div().col().child(div().h(1.).bg(p.border)).child(
            div()
                .row()
                .items_center()
                .h(27.)
                .px(12.)
                .bg(p.chrome)
                .child(text(self.repo.clone()).text_size(12.).text_color(p.text_dim))
                .child(div().grow())
                .child(text(details.unwrap_or_default()).text_size(12.).text_color(p.text_dim)),
        )
    }
