    pub fn active_tab(&self) -> Option<&Tab> {
        let ws = self.workspace()?;
        ws.tabs.get(ws.active?)
    }

    pub fn active_editor(&self) -> Option<&Editor> {
        if self.workspace()?.showing_diff { None } else { self.active_tab().map(|tab| &tab.editor) }
    }

    pub fn active_editor_mut(&mut self) -> Option<&mut Editor> {
        let ws = self.workspaces.get_mut(&self.repo)?;
        let ix = ws.active?;
        if ws.showing_diff { None } else { ws.tabs.get_mut(ix).map(|tab| &mut tab.editor) }
    }

    /// Remembers this project's open tabs; the loose-files workspace (no project) is never saved.
    fn save_session(&mut self) {
        let Some(ws) = self.workspaces.get(&self.repo).filter(|_| !self.repo.is_empty()) else { return };
        let session = Session {
            tabs: ws.tabs.iter().map(|t| t.path.to_string_lossy().into_owned()).collect(),
            active: ws.active.and_then(|i| ws.tabs.get(i)).map(|t| t.path.to_string_lossy().into_owned()),
        };
        if self.config.sessions.get(&self.repo) != Some(&session) {
            self.config.sessions.insert(self.repo.clone(), session);
            self.config.save();
        }
    }

    /// Reopens the tabs a project had last time; files that vanished or can't be read are skipped.
    fn restore_session(&mut self) {
        let Some(session) = self.config.sessions.get(&self.repo).cloned() else { return };
        for tab in &session.tabs {
            let path = PathBuf::from(tab);
            if path.is_file() {
                self.open_tab(path, false);
            }
        }
        let ws = self.workspace_mut();
        ws.active = session.active.and_then(|a| ws.tabs.iter().position(|t| t.path == Path::new(&a)));
        ws.active = ws.active.or(if ws.tabs.is_empty() { None } else { Some(0) });
        self.error = None;
        self.focus = Focus::Tree;
    }

    pub fn open_file(&mut self, path: PathBuf, preview: bool) {
        self.open_tab(path, preview);
        self.save_session();
    }

    /// Opens a file as a tab (or focuses its tab). A preview open replaces the current preview tab; a
    /// regular open pins whatever it lands on.
    fn open_tab(&mut self, path: PathBuf, preview: bool) {
        let name = path.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
        self.focus = Focus::Editor;
        self.blink_epoch = Instant::now();
        if let Some(ix) = self.workspace().and_then(|w| w.tabs.iter().position(|t| t.path == path)) {
            let ws = self.workspace_mut();
            if !preview {
                ws.tabs[ix].preview = false;
            }
            ws.active = Some(ix);
            ws.showing_diff = false;
            return;
        }
        let opened = std::fs::metadata(&path)
            .map_err(|e| e.to_string())
            .and_then(|m| if m.len() > MAX_OPEN_BYTES { Err("file is too large to open".to_string()) } else { Ok(()) })
            .and_then(|_| std::fs::read(&path).map_err(|e| e.to_string()))
            .and_then(|bytes| String::from_utf8(bytes).map_err(|_| "not a UTF-8 text file".to_string()));
        let text = match opened {
            Ok(text) => text,
            Err(reason) => {
                self.error = Some(format!("Can't open {name}: {reason}"));
                return;
            }
        };
        self.error = None;
        let tab = Tab { path: path.clone(), title: name, preview, editor: Editor::new(&text, path) };
        let ws = self.workspace_mut();
        ws.showing_diff = false;
        let ix = match (preview, ws.tabs.iter().position(|t| t.preview)) {
            (true, Some(replace)) => {
                ws.tabs[replace] = tab;
                replace
            }
            _ => {
                ws.tabs.push(tab);
                ws.tabs.len() - 1
            }
        };
        ws.active = Some(ix);
    }

    pub fn activate_tab(&mut self, ix: usize) {
        let ws = self.workspace_mut();
        if ix < ws.tabs.len() {
            ws.active = Some(ix);
            ws.showing_diff = false;
            self.focus = Focus::Editor;
            self.blink_epoch = Instant::now();
            self.save_session();
        }
    }

    /// Closes a tab. A file with unsaved changes stays open until it is saved (no confirmation dialog yet).
    pub fn close_tab(&mut self, ix: usize) {
        let Some(tab) = self.workspace().and_then(|w| w.tabs.get(ix)) else { return };
        if tab.editor.doc.is_dirty() {
            self.close_confirm = Some(ix);
            return;
        }
        self.remove_tab(ix);
    }

    fn remove_tab(&mut self, ix: usize) {
        let ws = self.workspace_mut();
        ws.tabs.remove(ix);
        ws.active = match ws.active {
            _ if ws.tabs.is_empty() => None,
            Some(a) if a > ix => Some(a - 1),
            Some(a) if a == ix => Some(ix.min(ws.tabs.len() - 1)),
            other => other,
        };
        self.save_session();
    }

    fn begin_tab_drag(&mut self, ix: usize, x: f32) {
        self.tab_drag = Some((ix, x));
    }

    fn drag_tab(&mut self, x: f32) {
        let Some((ix, previous)) = self.tab_drag else { return };
        let Some(count) = self.workspace().map(|ws| ws.tabs.len()) else { return };
        let delta = x - previous;
        let target = if delta > 48. && ix + 1 < count { Some(ix + 1) } else if delta < -48. && ix > 0 { Some(ix - 1) } else { None };
        let Some(target) = target else { return };
        let ws = self.workspace_mut();
        ws.tabs.swap(ix, target);
        if ws.active == Some(ix) {
            ws.active = Some(target);
        } else if ws.active == Some(target) {
            ws.active = Some(ix);
        }
        self.tab_drag = Some((target, x));
    }

    fn end_tab_drag(&mut self) {
        self.tab_drag = None;
        self.save_session();
    }

    fn resolve_close(&mut self, save: bool, cx: &mut Cx) {
        let Some(ix) = self.close_confirm.take() else { return };
        if save {
            let Some(tab) = self.workspace_mut().tabs.get_mut(ix) else { return };
            let name = tab.title.clone();
            match std::fs::write(&tab.path, tab.editor.doc.text_for_save()) {
                Ok(()) => tab.editor.doc.mark_saved(),
                Err(e) => { self.error = Some(format!("Can't save {name}: {e}")); return; }
            }
        }
        self.remove_tab(ix);
        self.touched(cx);
    }

    // ---- worktrees and diffs -----------------------------------------------------------------

    fn refresh_worktrees(&mut self) {
        self.worktrees.clear();
        self.changes.clear();
        self.selected_worktree = None;
        self.selected_change = None;
        self.worktree_issue = None;
        if self.repo.is_empty() {
            return;
        }
        let saved = self.config.pins.get(&self.repo).cloned().unwrap_or_default();
        match scan_repo(self.repo.clone(), saved) {
            Ok(ScanOutcome::Loaded(scan)) => {
                self.worktrees = scan.worktrees;
                self.pins = scan.pins;
                self.branches = scan.branches;
                self.config.pins.insert(self.repo.clone(), self.pins.clone());
                self.config.save();
            }
            Ok(ScanOutcome::Issue(issue)) => self.worktree_issue = Some(issue),
            Err(reason) => self.error = Some(format!("Can't scan git repository: {reason}")),
        }
    }

    fn select_worktree(&mut self, ix: usize) {
        let Some(worktree) = self.worktrees.get(ix) else { return };
        self.selected_worktree = Some(ix);
        self.selected_change = None;
        self.changes.clear();
        self.error = None;
        let base = self.pins.get(&worktree.path).cloned().unwrap_or_default();
        let branch = worktree.branch.clone();
        match diff::diff_against_base(worktree.path.clone(), base) {
            Ok(result) => self.changes = result.files,
            Err(reason) => self.error = Some(format!("Can't load changes: {reason}")),
        }
        if self.git_graph_open && self.graph_follow {
            if let Some(branch) = branch { self.load_graph(branch); }
        }
    }

    fn set_worktree_base(&mut self, ix: usize, branch: String) {
        let Some(worktree) = self.worktrees.get(ix) else { return };
        self.pins.insert(worktree.path.clone(), branch);
        self.config.pins.insert(self.repo.clone(), self.pins.clone());
        self.config.save();
        self.branch_picker = None;
        self.refresh_worktrees();
        self.select_worktree(ix);
    }

    fn open_branch_picker(&mut self, target: BranchPickerTarget, anchor: (f32, f32)) {
        self.branch_picker = Some(BranchPicker { target, anchor, query: String::new(), collapsed: HashSet::new(), highlighted: 0 });
    }

    fn picker_rows(&self) -> Vec<BranchRow> {
        self.branch_picker.as_ref().map_or_else(Vec::new, |picker| branches::flatten(&self.branches, &picker.collapsed, &picker.query))
    }

    fn activate_picker(&mut self, row: usize) {
        let Some(picked) = self.picker_rows().into_iter().nth(row) else { return };
        match picked {
            BranchRow::Folder { full_path, .. } => {
                let Some(picker) = &mut self.branch_picker else { return };
                if !picker.collapsed.remove(&full_path) {
                    picker.collapsed.insert(full_path);
                }
            }
            BranchRow::Branch { full_path, .. } => {
                let Some(target) = self.branch_picker.as_ref().map(|picker| picker.target) else { return };
                match target {
                    BranchPickerTarget::WorktreeBase(ix) => self.set_worktree_base(ix, full_path),
                    BranchPickerTarget::Graph => {
                        self.graph_follow = false;
                        self.load_graph(full_path);
                    }
                }
            }
        }
    }

    fn picker_key(&mut self, key: &gyeol::Key, text: Option<&str>, cx: &Cx) -> bool {
        if self.branch_picker.is_none() {
            return false;
        }
        match key {
            gyeol::Key::Named(NamedKey::Escape) => self.branch_picker = None,
            gyeol::Key::Named(NamedKey::Enter) => {
                let highlighted = self.branch_picker.as_ref().map(|picker| picker.highlighted).unwrap_or(0);
                self.activate_picker(highlighted);
            }
            gyeol::Key::Named(NamedKey::ArrowUp) => {
                if let Some(picker) = &mut self.branch_picker {
                    picker.highlighted = picker.highlighted.saturating_sub(1);
                }
            }
            gyeol::Key::Named(NamedKey::ArrowDown) => {
                let last = self.picker_rows().len().saturating_sub(1);
                if let Some(picker) = &mut self.branch_picker {
                    picker.highlighted = (picker.highlighted + 1).min(last);
                }
            }
            gyeol::Key::Named(NamedKey::Backspace) => {
                if let Some(picker) = &mut self.branch_picker {
                    picker.query.pop();
                    picker.highlighted = 0;
                }
            }
            _ if !cx.modifiers.command() => {
                if let (Some(input), Some(picker)) = (text, &mut self.branch_picker) {
                    picker.query.push_str(input);
                    picker.highlighted = 0;
                }
            }
            _ => {}
        }
        true
    }

    fn picker_ime(&mut self, ime: &gyeol::Ime) -> bool {
        let Some(picker) = &mut self.branch_picker else { return false };
        if let gyeol::Ime::Commit(input) = ime {
            picker.query.push_str(input);
            picker.highlighted = 0;
        }
        true
    }

    fn remove_worktree(&mut self, path: String) {
        match madi_git::worktree::remove_worktree(self.repo.clone(), path.clone()) {
            Ok(()) => { self.pins.remove(&path); self.config.pins.insert(self.repo.clone(), self.pins.clone()); self.config.save(); self.refresh_worktrees(); }
            Err(reason) => self.error = Some(format!("Can't remove worktree: {reason}")),
        }
    }

    fn open_diff(&mut self, ix: usize) {
        let Some(file) = self.changes.get(ix) else { return };
        self.selected_change = Some(ix);
        let diff = DiffTab { title: file.path.clone(), file: FileDiff {
            path: file.path.clone(), status: file.status.clone(), additions: file.additions, deletions: file.deletions,
            section: file.section, binary: file.binary, lines: file.lines.iter().map(|line| madi_git::diff::DiffLine {
                tag: line.tag, old_lineno: line.old_lineno, new_lineno: line.new_lineno,
                segments: line.segments.iter().map(|segment| madi_git::diff::Segment { text: segment.text.clone(), emphasized: segment.emphasized }).collect(),
                skipped: line.skipped,
            }).collect(),
        } };
        let ws = self.workspace_mut();
        ws.diff = Some(diff);
        ws.showing_diff = true;
        self.focus = Focus::Editor;
    }

    fn close_diff(&mut self) {
        let ws = self.workspace_mut();
        ws.diff = None;
        ws.showing_diff = false;
    }

